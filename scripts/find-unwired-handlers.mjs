#!/usr/bin/env node
/**
 * Lists window.* handlers that are DEFINED but never referenced anywhere else in the source
 * (no onclick, no call site). They are "unwired": unused aliases, delegated wrappers, demos,
 * or features whose UI was removed. This is NOT a delete list — many are intentional WIP.
 * It is a reference so a human can decide, feature by feature, what is truly dead.
 *
 * Writes memory/unwired-handlers.md. Run: node scripts/find-unwired-handlers.mjs
 */
import { execSync } from 'child_process'
import fs from 'fs'

const defLines = execSync('grep -rhnoE "window\\.[a-zA-Z][a-zA-Z0-9]+ ?=" src/ --include=*.js').toString()
const defs = [...new Set([...defLines.matchAll(/window\.([a-zA-Z][a-zA-Z0-9]+)/g)].map((m) => m[1]))]

const files = execSync('find src -name "*.js"').toString().trim().split('\n')
const fileText = Object.fromEntries(files.map((f) => [f, fs.readFileSync(f, 'utf8')]))
const blob = Object.values(fileText).join('\n')

// Grab each handler's one-line definition (to detect pure-delegation aliases).
function defOf(h) {
  for (const f of files) {
    const m = fileText[f].match(new RegExp('window\\.' + h + ' ?=([^\\n]*)'))
    if (m) return m[1].trim()
  }
  return ''
}

const unwired = []
for (const h of defs) {
  const n = (blob.match(new RegExp('\\b' + h + '\\b', 'g')) || []).length
  if (n <= 1) unwired.push(h)
}

const cat = { alias: [], setter: [], demo: [], identity: [], guardian: [], gamification: [], other: [] }
for (const h of unwired) {
  const def = defOf(h)
  const isAlias = /^(async\s*)?\([^)]*\)\s*=>\s*window\.\w+\??\.?\([^)]*\)\s*$/.test(def)
  const isSetter = /^\([^)]*\)\s*=>\s*(window\.)?setState/.test(def)
  if (isAlias) cat.alias.push(`${h}  ->  ${def}`)
  else if (isSetter) cat.setter.push(`${h}  ->  ${def}`)
  else if (/Demo/.test(h)) cat.demo.push(h)
  else if (/identity|verif|document|selfie|ageVerif/i.test(h)) cat.identity.push(h)
  else if (/guardian/i.test(h)) cat.guardian.push(h)
  else if (/badge|challenge|team|title|frame|booster|avatar|trust|reward|season|points|level/i.test(h)) cat.gamification.push(h)
  else cat.other.push(h)
}

const md = []
md.push('# Unwired handlers — defined but never referenced in source')
md.push('')
md.push(`Generated by \`scripts/find-unwired-handlers.mjs\`. **${unwired.length}** of the window handlers are`)
md.push('defined but have **no call site / no onclick** in the source. They are NOT automatically dead —')
md.push('many are unused aliases, delegated wrappers, demos, or features whose UI was temporarily removed.')
md.push('This is a **reference for human judgement**, not a delete list. Decide feature by feature.')
md.push('')
const order = [['alias', 'Unused aliases / pure delegation wrappers (delegate to another window.* handler)'],
  ['setter', 'One-line setState close/setter handlers with no onclick site (often a duplicate close name)'],
  ['demo', 'Demo / showcase handlers'],
  ['identity', 'Identity verification (gated off in alpha)'],
  ['guardian', 'Guardian (UI possibly removed)'],
  ['gamification', 'Gamification (hidden in alpha)'],
  ['other', 'Other — needs case-by-case review']]
for (const [k, label] of order) {
  md.push(`## ${label} (${cat[k].length})`)
  md.push('')
  for (const item of cat[k].sort()) md.push(`- \`${item}\``)
  md.push('')
}
fs.writeFileSync('memory/unwired-handlers.md', md.join('\n'))
console.log(`Wrote memory/unwired-handlers.md — ${unwired.length} unwired handlers`)
for (const [k] of order) console.log(`  ${k}: ${cat[k].length}`)
