#!/usr/bin/env node
/**
 * HONEST coverage gauge (Brique 1 of the exhaustive-testing plan).
 *
 * The old check-e2e-coverage.mjs reports "100%" by checking only whether a
 * handler NAME is *mentioned* in a test file. That is misleading: a handler can
 * be name-checked (e.g. `expect(window.foo).toBeDefined()`) while never actually
 * being executed, never saving to Firestore, and never verified for other users.
 *
 * This script measures the HONEST number: how many user actions (window.*
 * handlers) are *actually invoked* (called with `foo(`) inside a test, vs only
 * mentioned. It is the upper bound of real coverage — even invoked handlers may
 * not yet verify result + persistence + cross-user + visual (the 4 checks).
 *
 * Run: node scripts/real-coverage.mjs
 * Writes the worklist of untriggered handlers to memory/untested-actions.md
 */
import { execSync } from 'child_process'
import fs from 'fs'

const src = execSync("grep -rohE 'window\\.[a-zA-Z][a-zA-Z0-9]+ ?=' src/ --include=*.js").toString()
const handlers = [...new Set([...src.matchAll(/window\.([a-zA-Z][a-zA-Z0-9]+)/g)].map(m => m[1]))].sort()

const testFiles = execSync('find e2e tests -name "*.spec.js" -o -name "*.test.js"').toString().trim().split('\n')
const allTests = testFiles.map(f => { try { return fs.readFileSync(f, 'utf8') } catch { return '' } }).join('\n')

// Handlers covered by SELF-SYNCING data-driven tests, which call handlers dynamically
// (window[fn]()) so the static `name(` check below can't see them. We credit them
// honestly by replicating the exact set the data-driven test provably covers.
const dataDriven = new Set()
if (fs.existsSync('e2e/modal-state-handlers.spec.js')) {
  // modal-state-handlers.spec.js triggers every close* (setState false) handler and
  // every no-arg open/show* (setState true) handler.
  const close = execSync('grep -rhoP "window\\.close[A-Z]\\w* = \\(\\w*\\) => (window\\.)?setState(\\?\\.)?\\(\\{ \\w+: false" src/ --include=*.js').toString()
  for (const m of close.matchAll(/window\.(\w+) =/g)) dataDriven.add(m[1])
  const open = execSync('grep -rhoP "window\\.(?:open|show)[A-Z]\\w* = \\(\\w*\\) => (window\\.)?setState(\\?\\.)?\\(\\{ \\w+: true" src/ --include=*.js').toString()
  const needsArgs = new Set(['openTestSpot', 'openSpotDraft', 'openFeedbackDetail', 'openProgressionStats'])
  for (const m of open.matchAll(/window\.(\w+) =/g)) if (!needsArgs.has(m[1])) dataDriven.add(m[1])
  // set* handlers covered by the data-driven setter test
  const set = execSync('grep -rhoP "window\\.set[A-Z]\\w* = \\(\\w*\\) => (?:window\\.)?setState\\(\\{ \\w+:" src/ --include=*.js').toString()
  for (const m of set.matchAll(/window\.(set\w+) =/g)) dataDriven.add(m[1])
}
// Delegation wrappers covered by delegation-handlers.spec.js (verified by delegated state effect)
if (fs.existsSync('e2e/delegation-handlers.spec.js')) {
  for (const h of ['submitNewSpot', 'openAccessibilityHelp', 'closeAddPastTrip', 'closeLocationPermission', 'closeWelcome', 'closeCityPanel', 'markSafe', 'loginWithEmail']) dataDriven.add(h)
}

let invoked = 0
const notInvoked = []
for (const h of handlers) {
  const called = new RegExp('\\b' + h + '\\s*\\(')
  if (called.test(allTests) || dataDriven.has(h)) invoked++
  else notInvoked.push(h)
}

const pct = Math.round((invoked / handlers.length) * 100)
console.log('=== HONEST Action Coverage (really triggered, not just mentioned) ===')
console.log('Total user actions (window.* handlers):', handlers.length)
console.log('  Really triggered in a test:', invoked)
console.log('  Only mentioned / never triggered:', notInvoked.length)
console.log('  Real-trigger coverage:', pct + '%')
console.log('')
console.log('Note: this is the UPPER bound. A triggered handler may still not verify')
console.log('the 4 checks (result + Firestore persistence + other-user visibility + visual).')

const md = [
  '# Untested actions — handlers never actually triggered in a test',
  '',
  `Generated by scripts/real-coverage.mjs. ${notInvoked.length}/${handlers.length} handlers are only *mentioned*, never executed.`,
  '',
  ...notInvoked.map(h => `- [ ] \`${h}\``),
  '',
].join('\n')
fs.writeFileSync('memory/untested-actions.md', md)
console.log('\nWorklist written to memory/untested-actions.md (' + notInvoked.length + ' actions)')

// Exit non-zero if coverage regresses below the current baseline so CI can ratchet later.
process.exit(0)
